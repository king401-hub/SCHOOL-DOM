"""A student's own "My ID Card" page (student_my_id_card) used to stay
locked behind "Your school admin has not generated your ID card yet."
until an admin visited the admin ID Cards screen, selected that exact
student, and clicked download - the only code path that ever set
StudentProfile.id_card_generated_at. For a school with any real number of
students that's a one-by-one manual gate nobody reliably clears.

Every real place a StudentProfile gets created now sets
id_card_generated_at itself, so a student can see their own card
immediately - these tests cover each of those places independently,
since they're separate code paths that could each regress on their own.
"""
from unittest.mock import patch

from django.test import TestCase
from django.utils import timezone
from rest_framework.test import APIClient

from academic.models import Class
from ai_secretary.tools import SecretaryTools
from core.models import SchoolTenant
from finance.services import get_or_create_activation_credit_pool
from tenants.models import Tenant
from users.models import StudentProfile, User


def _my_id_card(client):
    return client.get("/api/app/id-cards/my/")


class IdCardAutoGeneratedOnCreationTests(TestCase):
    def setUp(self):
        self.school = SchoolTenant.objects.create(name="Card School", schema_name="card_school", is_active=True)
        self.legacy_tenant = Tenant.objects.create(name="Card School Legacy", slug="card_school")
        self.admin = User.objects.create_user(
            email="admin@cardschool.edu", password="AdminPass123", first_name="Ada", last_name="Min",
            role="school_admin", tenant=self.school, is_active=True, is_verified=True,
        )
        self.client = APIClient()

    @patch("users.views.ADMIN_OTP_ENABLED", False)
    def test_a_student_the_admin_creates_can_see_their_card_right_away(self):
        self.client.force_authenticate(user=self.admin)
        response = self.client.post(
            "/api/app/students/create/",
            {
                "student_email": "new.student@cardschool.edu", "first_name": "New", "last_name": "Student",
                "guardian_name": "Guardian", "guardian_phone": "08010000001",
                "student_password": "StudentPass123", "confirm_student_password": "StudentPass123",
            },
        )
        self.assertEqual(response.status_code, 201, response.data)
        student_user = User.objects.get(email="new.student@cardschool.edu")

        self.client.force_authenticate(user=student_user)
        card_response = _my_id_card(self.client)
        self.assertEqual(card_response.status_code, 200, card_response.data)
        self.assertTrue(card_response.data["available"], card_response.data.get("message"))

    def test_a_self_registered_student_can_see_their_card_right_away(self):
        pool = get_or_create_activation_credit_pool(self.school)
        pool.balance = 5
        pool.save(update_fields=["balance", "updated_at"])
        self.school.school_type = SchoolTenant.NON_K12
        self.school.save(update_fields=["school_type"])

        response = self.client.post(
            "/api/auth/register/",
            data={
                "first_name": "Self", "last_name": "Registered", "email": "self.reg@cardschool.edu",
                "password": "StudentPass123", "confirm_password": "StudentPass123", "role": "student",
                "guardian_name": "Guardian Person", "phone": "08010000001",
                "school_code": self.school.schema_name, "terms_accepted": True,
            },
            format="json",
        )
        self.assertEqual(response.status_code, 201, response.data)
        student_user = User.objects.get(email="self.reg@cardschool.edu")

        self.client.force_authenticate(user=student_user)
        card_response = _my_id_card(self.client)
        self.assertEqual(card_response.status_code, 200, card_response.data)
        self.assertTrue(card_response.data["available"], card_response.data.get("message"))

    def test_a_student_the_ai_secretary_creates_can_see_their_card_right_away(self):
        class_obj = Class.objects.create(name="JSS1", section="A", tenant=self.legacy_tenant)
        tools = SecretaryTools(tenant=self.school, requesting_user=self.admin)
        result = tools.create_student(
            name="Ai Created",
            phone="+2348010000002",
            class_name="JSS1",
            guardian_name="Guardian Person",
        )
        self.assertEqual(result.get("status"), "success", result)
        profile = StudentProfile.objects.get(user__tenant=self.school, current_class=class_obj)
        self.assertIsNotNone(profile.id_card_generated_at)
        self.assertLessEqual(profile.id_card_generated_at, timezone.now())
